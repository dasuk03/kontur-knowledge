export function qualificationLabel(progress: number) {
  if (progress >= 100) return "Специалист маршрута";
  if (progress >= 70) return "Диагност";
  if (progress >= 35) return "Электромонтёр";
  if (progress > 0) return "Стажёр";
  return "Новый сотрудник";
}
